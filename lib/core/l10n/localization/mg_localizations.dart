class MalagasyMaterialLocalizationsDelegate
    extends LocalizationsDelegate<MaterialLocalizations> {
  const MalagasyMaterialLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => locale.languageCode == 'mg';

  @override
  Future<MaterialLocalizations> load(Locale locale) {
    return SynchronousFuture(
      MalagasyMaterialLocalizations(
        localeName: 'mg',
        fullYearFormat: intl.DateFormat('y', 'fr'),
        compactDateFormat: intl.DateFormat('yMd', 'fr'),
        shortDateFormat: intl.DateFormat('yMMMd', 'fr'),
        mediumDateFormat: intl.DateFormat('EEE, MMM d, y', 'fr'),
        longDateFormat: intl.DateFormat('EEEE, MMMM d, y', 'fr'),
        yearMonthFormat: intl.DateFormat('MMMM y', 'fr'),
        shortMonthDayFormat: intl.DateFormat('MMM d', 'fr'),
        decimalFormat: intl.NumberFormat('#,##0.###', 'fr'),
        twoDigitZeroPaddedFormat: intl.NumberFormat('00', 'fr'),
      ),
    );
  }

  @override
  bool shouldReload(MalagasyMaterialLocalizationsDelegate old) => false;
}

